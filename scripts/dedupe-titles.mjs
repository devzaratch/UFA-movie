// Duplicate resolver (plan #3 item #5 + plan #4 item #7).
//
// Three relations decide that two entries are the same film:
//   1. identical normalized title (Lao/Thai-insensitive, marks ignored),
//   2. identical title once the "(YYYY)" is removed — the same film re-listed
//      under another year,
//   3. identical stream: the same m3u8 url (movies) or the same episode set
//      (series) — the same video file can never be two different films.
//
// Relations are merged transitively (union-find), so a chain like
// "same url" + "same title" collapses into one canonical entry.
//
// Writes src/data/duplicates.js: DUPLICATE_TO_CANONICAL = { duplicateId: canonicalId }.
// Canonical pick: alive stream first (not in DEAD_IDS), then the smaller id.
// The canonical page keeps its URL; duplicates stay online (old links keep
// working) but point their canonical/OG at the main entry and are left out of
// the homepage catalog and sitemap.
//
// Usage: node scripts/dedupe-titles.mjs
import { writeFileSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { normalizeText, stripMarks } from '../src/lib/search.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = join(ROOT, 'src', 'data', 'duplicates.js');

const { movieDatabase } = await import(pathToFileURL(join(ROOT, 'src', 'data', 'movies.js')).href);
const { DEAD_IDS } = await import(pathToFileURL(join(ROOT, 'src', 'data', 'dead-links.js')).href);

const num = (id) => parseInt(id.slice(1), 10) || 0;
const titleKey = (m) => stripMarks(normalizeText(m.title || ''));
const yearlessKey = (m) => stripMarks(normalizeText((m.title || '').replace(/\(\s*\d{4}\s*\)/g, '')));
// The exact video set of an entry (movies have one url, series have episodes).
const streamKey = (m) => {
    const urls = [m.url, ...(Array.isArray(m.episodes) ? m.episodes.map((e) => e.url) : [])].filter(Boolean);
    if (!urls.length) return null;
    return urls.map((u) => String(u).trim()).sort().join('|');
};

// ── union-find ───────────────────────────────────────────────────────────────
const parent = new Map(movieDatabase.map((m) => [m.id, m.id]));
const find = (a) => {
    let r = a;
    while (parent.get(r) !== r) r = parent.get(r);
    while (parent.get(a) !== r) { const next = parent.get(a); parent.set(a, r); a = next; }
    return r;
};
const union = (a, b) => {
    const ra = find(a);
    const rb = find(b);
    if (ra !== rb) parent.set(rb, ra);
};

// Link every member of a bucket to its first member.
const linkBuckets = (buckets) => {
    for (const ids of buckets.values()) {
        if (ids.length < 2) continue;
        const first = ids[0];
        for (const id of ids.slice(1)) union(first, id);
    }
};

const bucketize = (keyOf) => {
    const buckets = new Map();
    for (const m of movieDatabase) {
        const key = keyOf(m);
        if (!key) continue;
        if (!buckets.has(key)) buckets.set(key, []);
        buckets.get(key).push(m.id);
    }
    return buckets;
};

linkBuckets(bucketize(titleKey));
// Same film re-listed under another year — only trusted when the video file is
// identical too ("The Crow (1994)" and "The Crow (2024)" are different films).
linkBuckets(bucketize((m) => (streamKey(m) ? `${yearlessKey(m)}||${streamKey(m)}` : null)));
linkBuckets(bucketize(streamKey));

// ── canonical + map ──────────────────────────────────────────────────────────
const byRoot = new Map();
for (const m of movieDatabase) {
    const r = find(m.id);
    if (!byRoot.has(r)) byRoot.set(r, []);
    byRoot.get(r).push(m);
}
const ranked = (list) => [...list].sort((a, b) => {
    const da = DEAD_IDS.has(a.id) ? 1 : 0;
    const db = DEAD_IDS.has(b.id) ? 1 : 0;
    if (da !== db) return da - db;          // alive first
    return num(a.id) - num(b.id);           // older (smaller) id first
});

const map = {};
const reasons = { title: 0, yearless: 0, stream: 0 };
let dupCount = 0;
for (const list of byRoot.values()) {
    if (list.length < 2) continue;
    const [canonical, ...rest] = ranked(list);
    for (const m of rest) {
        map[m.id] = canonical.id;
        dupCount++;
        if (titleKey(m) === titleKey(canonical)) reasons.title++;
        else if (yearlessKey(m) === yearlessKey(canonical)) reasons.yearless++;
        else reasons.stream++;
    }
}

const entries = Object.entries(map).map(([d, c]) => `    '${d}': '${c}',`).join('\n');
writeFileSync(
    OUT_FILE,
    '// AUTO-GENERATED by scripts/dedupe-titles.mjs — do not edit by hand.\n'
    + '// Duplicate entries mapped to their canonical id (same title, same title\n'
    + '// ignoring the year, or the same stream url). Duplicates stay online (old\n'
    + '// links keep working) but canonical/OG point at the main entry and they are\n'
    + '// excluded from the homepage catalog and sitemap.\n'
    + `// Last run: ${new Date().toISOString()} (${dupCount} duplicates, ${byRoot.size} groups)\n`
    + `export const DUPLICATE_TO_CANONICAL = {\n${entries}\n};\n`,
    'utf8',
);

console.log(`duplicates mapped: ${dupCount}`);
console.log(`  by title: ${reasons.title}  by year-only: ${reasons.yearless}  by stream url: ${reasons.stream}`);
for (const [d, c] of Object.entries(map).slice(0, 10)) console.log(`  ${d} -> ${c}`);
