// Small poster thumbnails (plan item #8).
// The sidebar "แนะนำ" lists show 36×54 posters; loading a full poster there
// costs ~38KB each on mobile. This script writes 120px-wide webp thumbnails to
// public/thumbs/ and a map in src/data/thumbs-local.js.
//
// Cards keep the normal mirrored poster (already ~20-40KB) and only get
// explicit width/height in the markup to stop layout shift (CLS).
//
// Usage: node scripts/gen-thumbs.mjs [--fresh]
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, extname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const POSTERS = join(ROOT, 'public', 'posters');
const OUT_DIR = join(ROOT, 'public', 'thumbs');
const MAP_FILE = join(ROOT, 'src', 'data', 'thumbs-local.js');
const fresh = process.argv.includes('--fresh');
const WIDTH = 120;

mkdirSync(OUT_DIR, { recursive: true });

const files = readdirSync(POSTERS).filter((f) => /\.(jpe?g|png|webp|gif)$/i.test(f));
console.log(`posters found: ${files.length}`);

const map = {};
let made = 0, skipped = 0, failed = 0;

for (const file of files) {
    const id = basename(file, extname(file));
    const out = join(OUT_DIR, `${id}.webp`);
    if (!fresh && existsSync(out) && statSync(out).size > 0) {
        map[id] = `/thumbs/${id}.webp`;
        skipped++;
        continue;
    }
    try {
        await sharp(join(POSTERS, file))
            .resize({ width: WIDTH, withoutEnlargement: true })
            .webp({ quality: 72 })
            .toFile(out);
        map[id] = `/thumbs/${id}.webp`;
        made++;
    } catch (e) {
        failed++;
        if (failed < 5) console.warn(`  failed ${file}: ${e.message}`);
    }
    if ((made + skipped) % 400 === 0) console.log(`progress: ${made + skipped}/${files.length}`);
}

const entries = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b, 'en', { numeric: true }))
    .map(([id, p]) => `    '${id}': '${p}',`)
    .join('\n');

writeFileSync(
    MAP_FILE,
    '// AUTO-GENERATED by scripts/gen-thumbs.mjs — do not edit by hand.\n'
    + '// 120px-wide webp thumbnails for the small sidebar lists.\n'
    + `// Last run: ${new Date().toISOString()} (${Object.keys(map).length} thumbs)\n`
    + `export const LOCAL_THUMBS = {\n${entries}\n};\n`,
    'utf8',
);

let bytes = 0;
for (const f of readdirSync(OUT_DIR)) bytes += statSync(join(OUT_DIR, f)).size;
console.log(`done: ${made} made, ${skipped} skipped, ${failed} failed | total ${(bytes / 1024 / 1024).toFixed(1)} MB`);
