// Plan item #2: mirror posters of PLAYABLE titles into public/posters/ so the
// site stops depending on hotlinked external images (they die independently
// and break og:image too). Titles in DEAD_IDS keep their external poster.
//
// Output: src/data/posters-local.js  →  LOCAL_POSTERS = { id: '/posters/<id>.jpg' }
// Usage:  node scripts/mirror-posters.mjs [--fresh]
import { readFileSync, writeFileSync, existsSync, mkdirSync, statSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'public', 'posters');
const MAP_FILE = join(ROOT, 'src', 'data', 'posters-local.js');
const fresh = process.argv.includes('--fresh');

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';
const CONCURRENCY = 20;
const TIMEOUT_MS = 20000;

const { movieDatabase } = await import(pathToFileURL(join(ROOT, 'src', 'data', 'movies.js')).href);
const { DEAD_IDS } = await import(pathToFileURL(join(ROOT, 'src', 'data', 'dead-links.js')).href);

mkdirSync(OUT_DIR, { recursive: true });

// Pick playable titles with a poster url
const targets = movieDatabase.filter((m) => !DEAD_IDS.has(m.id) && m.poster);
console.log(`playable titles: ${targets.length}`);

function looksLikeImage(buf) {
    if (!buf || buf.length < 12) return false;
    const b = buf;
    if (b[0] === 0xff && b[1] === 0xd8) return true;                    // JPEG
    if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return true; // PNG
    if (b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46) return true; // WEBP (RIFF)
    if (b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46) return true;   // GIF
    return false;
}

function extOf(url, buf) {
    try {
        const p = new URL(url).pathname.toLowerCase();
        const m = p.match(/\.(jpe?g|png|webp|gif)$/);
        if (m) return '.' + m[1].replace('jpeg', 'jpg');
    } catch {}
    if (buf) {
        if (buf[0] === 0x89) return '.png';
        if (buf[0] === 0x52 && buf[1] === 0x46) return '.webp';
    }
    return '.jpg';
}

async function fetchBuf(url, referer) {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
    try {
        const headers = { 'User-Agent': UA, Accept: 'image/*,*/*;q=0.8' };
        if (referer) headers.Referer = referer;
        const res = await fetch(url, { headers, signal: ctrl.signal, redirect: 'follow' });
        if (!res.ok) return null;
        const buf = Buffer.from(await res.arrayBuffer());
        return looksLikeImage(buf) ? buf : null;
    } catch {
        return null;
    } finally {
        clearTimeout(timer);
    }
}

async function downloadOne(m) {
    // existing file (unless --fresh)
    if (!fresh) {
        const existing = readdirSync(OUT_DIR).find((f) => f.startsWith(m.id + '.'));
        if (existing && statSync(join(OUT_DIR, existing)).size > 0) return { id: m.id, file: existing };
    }
    let buf = await fetchBuf(m.poster);
    if (!buf) buf = await fetchBuf(m.poster, 'https://boengnang.vercel.app/');
    if (!buf) return { id: m.id, file: null };
    const ext = extOf(m.poster, buf);
    const file = m.id + ext;
    writeFileSync(join(OUT_DIR, file), buf);
    return { id: m.id, file };
}

const need = [...targets];
const map = {};
let ok = 0, fail = 0, done = 0;
const pool = [];
async function worker() {
    while (need.length) {
        const m = need.pop();
        const r = await downloadOne(m);
        if (r.file) { map[r.id] = '/posters/' + r.file; ok++; } else fail++;
        done++;
        if (done % 250 === 0) console.log(`progress: ${done}/${targets.length}`);
    }
}
for (let i = 0; i < CONCURRENCY; i++) pool.push(worker());
await Promise.all(pool);

const entries = Object.entries(map)
    .map(([id, path]) => `    '${id}': '${path}',`)
    .join('\n');
writeFileSync(
    MAP_FILE,
    '// AUTO-GENERATED by scripts/mirror-posters.mjs — do not edit by hand.\n'
    + '// Local poster paths for playable titles (mirrored from the external urls).\n'
    + `// Last run: ${new Date().toISOString()} (${ok} mirrored, ${fail} failed)\n`
    + `export const LOCAL_POSTERS = {\n${entries}\n};\n`,
    'utf8',
);

let totalBytes = 0;
for (const f of readdirSync(OUT_DIR)) totalBytes += statSync(join(OUT_DIR, f)).size;
console.log(`done: ${ok} mirrored, ${fail} failed, total ${(totalBytes / 1024 / 1024).toFixed(1)} MB`);
